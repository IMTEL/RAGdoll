"""Message feedback domain models."""

from datetime import datetime
from typing import Literal

from pydantic import BaseModel, Field


# How the counsellor rated an agent reply. The same words label each entry
# in the prompt, so keep them readable for the language model.
Rating = Literal["good", "bad"]


class MessageFeedback(BaseModel):
    """Feedback from a counsellor on a single agent reply.

    A counsellor rates replies while testing an agent, so that the agent
    learns how to answer. The most recent feedback for an agent is added to
    its prompt on every chat turn, from any client (The Candidate included).

    RAGdoll does not store conversations, so the rated reply and the user
    message it answered are stored as text in the feedback itself.

    Attributes:
        id: Unique identifier for the feedback (generated by the DAO)
        agent_id: ID of the agent whose reply was rated
        author_id: ID of the user (counsellor) who gave the feedback
        rating: Whether the reply was good or bad
        agent_message: The rated agent reply
        user_message: The user message the agent was answering
        comment: Optional free-text comment from the counsellor
        created_at: Timestamp when the feedback was given
    """

    id: str | None = Field(default=None, description="Unique feedback identifier")
    agent_id: str = Field(..., description="Agent whose reply was rated")
    author_id: str = Field(..., description="User that gave the feedback")
    rating: Rating = Field(..., description="Whether the reply was good or bad")
    agent_message: str = Field(
        ..., min_length=1, max_length=4000, description="The rated agent reply"
    )
    user_message: str = Field(
        default="", max_length=4000, description="The user message it answered"
    )
    comment: str = Field(default="", max_length=500, description="Optional comment")
    created_at: datetime = Field(
        default_factory=datetime.now, description="Creation timestamp"
    )
